-- ── 3. Split one expense into two ─────────────────────────────────────────
-- Used by the week view when part of a cost belongs in another week.
-- The original row keeps its identity and takes original_amount on
-- original_date; the remainder becomes a new row on split_date.
--
-- amount_mxn is rebuilt from the original row's own rate rather than from
-- today's rate. Both halves therefore keep the exchange rate the expense was
-- recorded at, and the two amount_mxn values still add up to the original.
create or replace function public.split_expense(
  expense_id      uuid,
  user_id         uuid,
  original_amount numeric,
  original_date   text,
  split_amount    numeric,
  split_date      text
)
returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_expense_id uuid := expense_id;
  v_user_id    uuid := user_id;
  v_row        public.expenses%rowtype;
  v_rate       numeric;
begin
  if original_amount <= 0 or split_amount <= 0 then
    raise exception 'split amounts must both be greater than zero';
  end if;

  select * into v_row
    from public.expenses e
   where e.id = v_expense_id and e.user_id = v_user_id;

  if not found then
    raise exception 'expense % not found for this user', v_expense_id;
  end if;

  -- The rate this expense was originally written at.
  v_rate := v_row.amount_mxn / v_row.amount;

  update public.expenses e
     set amount     = original_amount,
         amount_mxn = round(original_amount * v_rate, 2),
         "date"     = original_date::date,
         updated_at = now()
   where e.id = v_expense_id and e.user_id = v_user_id;

  -- The new half is a manual row. It deliberately does not inherit
  -- recurring_rule_id: it was not generated by a rule, and copying the link
  -- would collide with the one-row-per-rule-per-day index in migration 012.
  insert into public.expenses (
    user_id, amount, currency_id, amount_mxn, category_id, "date",
    notes, is_recurring, projected_cost_id
  )
  values (
    v_row.user_id,
    split_amount,
    v_row.currency_id,
    round(split_amount * v_rate, 2),
    v_row.category_id,
    split_date::date,
    v_row.notes,
    false,
    v_row.projected_cost_id
  );
end;
$$;
