-- ══════════════════════════════════════════════════════════════════════════
-- Database functions called over RPC
-- Run once in the Supabase SQL editor, after 001-010.
-- Idempotent — create or replace throughout.
--
-- These exist because week_number and week_year on expenses and earnings are
-- GENERATED columns. PostgREST refuses to write a generated column, and it
-- sends every column of a PATCH body, so changing a date through the normal
-- REST path fails. These functions change the date server side and let
-- Postgres recompute the week.
--
-- Two conventions matter for all three:
--
--   1. Parameter names are fixed. PostgREST matches arguments by name, so
--      they must stay exactly as the Python call sites spell them, including
--      the user_id parameter that collides with the user_id column. Each
--      body copies the parameters into v_ locals before touching a table so
--      that collision can never silently resolve to the column.
--
--   2. Every statement filters on user_id as well as the row id. These run
--      under the service role, which bypasses row level security, so this
--      filter is the only thing standing between one user and another user's
--      rows. It is not redundant.
-- ══════════════════════════════════════════════════════════════════════════


-- ── 1. Move an expense to a different date ────────────────────────────────
-- Called from expenses/service.py when a PATCH includes a date.
create or replace function public.update_expense_date(
  expense_id uuid,
  user_id    uuid,
  new_date   text
)
returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_expense_id uuid := expense_id;
  v_user_id    uuid := user_id;
  v_new_date   date := new_date::date;
begin
  update public.expenses e
     set "date"     = v_new_date,
         updated_at = now()
   where e.id      = v_expense_id
     and e.user_id = v_user_id;
end;
$$;


