-- Remove the carry-forward movements (defect 31)
-- Run once in the Supabase SQL editor, AFTER a fresh backup and AFTER the
-- preview below. Idempotent — a second run deletes nothing.
--
-- Until 02/11/2026 the Dashboard wrote each month's carry-forward as a real
-- expense or earning on the 1st, with a note like "Carry-forward · Oct 2026".
-- Net worth, totals, trends and projected vs real then counted that money a
-- second time. The carry-forward is now computed as the month's opening
-- balance and never written, so these rows are only the double count.
--
-- A row is removed only if it matches everything the old code wrote: the
-- exact note pattern, dated the 1st, not generated by a recurring rule and
-- not marked recurring. A movement a user typed by hand would have to copy
-- all of that to be caught.
--
-- Preview — run this first and read every row:
--
--   select 'expense' as kind, user_id, "date", amount_mxn, notes
--     from public.expenses
--    where notes ~ '^Carry-forward · [A-Z][a-z]{2} [0-9]{4}$'
--      and extract(day from "date") = 1
--      and recurring_rule_id is null and is_recurring = false
--   union all
--   select 'earning', user_id, "date", amount_mxn, notes
--     from public.earnings
--    where notes ~ '^Carry-forward · [A-Z][a-z]{2} [0-9]{4}$'
--      and extract(day from "date") = 1
--      and recurring_rule_id is null and is_recurring = false
--   order by 2, 3;
-- ══════════════════════════════════════════════════════════════════════════

delete from public.expenses
 where notes ~ '^Carry-forward · [A-Z][a-z]{2} [0-9]{4}$'
   and extract(day from "date") = 1
   and recurring_rule_id is null
   and is_recurring = false;

delete from public.earnings
 where notes ~ '^Carry-forward · [A-Z][a-z]{2} [0-9]{4}$'
   and extract(day from "date") = 1
   and recurring_rule_id is null
   and is_recurring = false;
